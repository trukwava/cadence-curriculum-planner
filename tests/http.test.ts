import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {once} from 'node:events';
import type {AddressInfo} from 'node:net';
const folder=mkdtempSync(join(tmpdir(),'northstar-http-test-'));
process.env.NODE_ENV='test';process.env.DB_PATH=join(folder,'integration.sqlite');
const {app}=await import('../src/server/server.js');
app.listen(0,'127.0.0.1');await once(app,'listening');
const port=(app.address() as AddressInfo).port,base=`http://127.0.0.1:${port}`;
const req=(path:string,options?:RequestInit)=>fetch(base+path,options);
const post=(path:string,x:unknown)=>req(path,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(x)});
test('local HTML and compiled JavaScript serve correctly',async()=>{
 const html=await req('/');assert.equal(html.status,200);assert.match(await html.text(),/Curriculum recovery/);
 const js=await req('/dist/app.js');assert.equal(js.status,200);assert.match(await js.text(),/Generate recovery alternatives/);
 assert.match(html.headers.get('content-security-policy')||'',/script-src 'self'/);
 const jsPath=await req('/../../../../etc/passwd');assert.equal(jsPath.status,404);
});
test('HTTP calendar preview is side-effect-free; accepting updates versions and exports',async()=>{
 const state=await (await req('/api/state')).json() as any;const old=state.sections.find((x:any)=>x.id==='cte-tt').activePlan;
 const p=await (await post('/api/disruptions/preview',{sectionId:'cte-tt',date:'2026-11-24',start:'10:00',end:'11:15',reason:'Integration fixture'})).json() as any[];
 assert.equal(p.length,2);assert.equal(p.find(x=>x.strategy==='retain').result.feasible,false);assert.equal(p.find(x=>x.strategy==='defer').result.feasible,true);
 const before=await (await req('/api/state')).json() as any;assert.equal(before.sections[1].activePlan.id,old.id);
 const infeasible=await post(`/api/proposals/${p.find(x=>x.strategy==='retain').id}/accept`,{});assert.equal(infeasible.status,400);
 const good=p.find(x=>x.strategy==='defer');const ok=await post(`/api/proposals/${good.id}/accept`,{});assert.equal(ok.status,200);
 const after=await (await req('/api/state')).json() as any;const active=after.sections.find((x:any)=>x.id==='cte-tt').activePlan;
 assert.equal(active.versionNo,old.versionNo+1);assert.equal(after.sections.find((x:any)=>x.id==='cte-tt').disruptions.length,1);
 const csv=await (await req('/api/export/cte-tt.csv')).text();const lines=csv.trim().split('\r\n');assert.equal(lines.length-1,active.snapshot.result.allocations.length);assert.ok(lines.some(line=>line.startsWith('2026-11-19')));
 const ics=await (await req('/api/export/cte-tt.ics')).text();assert.equal((ics.match(/BEGIN:VEVENT/g)||[]).length,active.snapshot.result.allocations.length);assert.match(ics,/DTSTART:20261119T/);assert.match(ics,/X-WR-TIMEZONE:America\/New_York/);
 assert.ok(active.snapshot.result.allocations.every((a:any)=>csv.includes(`${a.date},${a.start},${a.end}`)));
});
test('HTTP teacher adjustment previews, rejects invalid moves, accepts and exports new times',async()=>{
 const st=await (await req('/api/state')).json() as any;
 const current=st.sections.find((s:any)=>s.id==='cte-tt').activePlan;
 // Existing disruption is accepted in preceding test: choose an available block and an unoccupied interval.
 const chosen=current.snapshot.result.allocations.find((a:any)=>a.lessonId==='lesson-16');
 assert.ok(chosen);
 const invalid=await post('/api/manual-moves/preview',{sectionId:'cte-tt',allocationId:chosen.id,targetSessionId:'invalid',start:'10:00'});
 assert.equal(invalid.status,400);
 // Reset to a predictable fixture for the positive HTTP flow.
 assert.equal((await post('/api/reset',{})).status,200);
 const baseline=await (await req('/api/state')).json() as any;
 const start=baseline.sections.find((s:any)=>s.id==='cte-tt').activePlan;
 const block=start.snapshot.result.allocations.find((a:any)=>a.lessonId==='lesson-18');
 const previewResponse=await post('/api/manual-moves/preview',{sectionId:'cte-tt',allocationId:block.id,targetSessionId:block.sessionId,start:'10:40'});
 assert.equal(previewResponse.status,200);
 const preview=await previewResponse.json() as any;
 assert.equal(preview.after.end,'11:05');
 assert.equal((await post(`/api/manual-moves/${preview.id}/accept`,{})).status,200);
 const revised=await (await req('/api/state')).json() as any;
 assert.equal(revised.sections.find((s:any)=>s.id==='cte-tt').activePlan.versionNo,start.versionNo+1);
 const csv=await (await req('/api/export/cte-tt.csv')).text();
 assert.match(csv,/2026-11-26,10:40,11:05/);
 const ics=await (await req('/api/export/cte-tt.ics')).text();
 assert.match(ics,/DTSTART:20261126T104000/);
});
test('HTTP occupied-slot rearrangement produces a reviewable versioned plan',async()=>{
 assert.equal((await post('/api/reset',{})).status,200);
 const state=await (await req('/api/state')).json() as any;
 const section=state.sections.find((x:any)=>x.id==='cte-tt');
 const before=section.activePlan;
 const source=before.snapshot.result.allocations.find((x:any)=>x.lessonId==='lesson-17'&&x.date==='2026-11-26');
 const target=before.snapshot.result.allocations.find((x:any)=>x.lessonId==='lesson-18');
 const invalid=await post('/api/manual-moves/preview',{sectionId:'cte-tt',allocationId:source.id,targetSessionId:target.sessionId,start:target.start});
 assert.equal(invalid.status,400);
 const response=await post('/api/manual-moves/rearrange',{sectionId:'cte-tt',allocationId:source.id,targetSessionId:target.sessionId,start:target.start});
 assert.equal(response.status,200);
 const proposal=await response.json() as any;
 assert.ok(proposal.changes.length>=2);assert.equal(proposal.status,'draft');
 const unchanged=await (await req('/api/state')).json() as any;
 assert.equal(unchanged.sections.find((x:any)=>x.id==='cte-tt').activePlan.id,before.id);
 assert.equal((await post(`/api/manual-moves/${proposal.id}/accept`,{})).status,200);
 const after=await (await req('/api/state')).json() as any;
 const version=after.sections.find((x:any)=>x.id==='cte-tt').activePlan;
 assert.equal(version.versionNo,before.versionNo+1);
 const csv=await (await req('/api/export/cte-tt.csv')).text();
 assert.ok(csv.includes(`2026-11-26,${target.start},11:10`));
 const ics=await (await req('/api/export/cte-tt.ics')).text();
 assert.ok(ics.includes('DTSTART:20261126T103500'));
});
